
package ejercicio5_sumatoria;


public class Ejercicio5_Sumatoria {

  
    public static void main(String[] args) {
        int num = 0;
        int sumatoria = 0;
        
        do
        {
            sumatoria += num;
            
        }while(num <= 50);
        
        
        System.out.println("La sumatoria de los numeros es "+sumatoria);
        
        
    }
    
    
}
